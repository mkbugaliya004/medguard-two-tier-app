
document.addEventListener("DOMContentLoaded", () => {
    const form = document.querySelector("#assessment-form");
    const result = document.querySelector("#assessment-result");

    if (!form || !result) {
        return;
    }

    form.addEventListener("submit", async (event) => {
        event.preventDefault();

        const formData = new FormData(form);

        const numericFields = [
            "age",
            "dose_mg",
            "heart_rate",
            "qtc_ms",
            "qrs_ms",
            "baseline_qrs_ms",
            "crcl",
            "lvef_percent",
            "potassium",
            "magnesium"
        ];

        const booleanFields = [
            "thyroid_tests_overdue",
            "liver_function_abnormal",
            "thyroid_function_abnormal",
            "multiple_rate_limiting_medicines",
            "structural_heart_disease",
            "long_qt_syndrome",
            "qt_prolonging_interaction",
            "bradycardia_symptoms"
        ];

        const patientData = {
            medicine: formData.get("medicine"),
            cardiac_diagnosis: formData.get("cardiac_diagnosis") || null
        };

        numericFields.forEach((field) => {
            patientData[field] = readNumber(formData, field);
        });

        booleanFields.forEach((field) => {
            patientData[field] = formData.get(field) === "true";
        });

        const validation = validateAssessment(patientData);

        if (!validation.valid) {
            result.textContent = validation.errors.join(" ");
            return;
        }

        result.textContent = "Assessing synthetic profile…";

        try {
            const assessment = await assessMedication(patientData);
            displayAssessment(assessment, result);
        } catch (error) {
            result.textContent =
                "Assessment failed. Check the API connection and try again.";
            console.error(error);
        }
    });

    form.addEventListener("reset", () => {
        result.textContent = "Ready for a new synthetic assessment.";
    });
});


function readNumber(formData, fieldName) {
    const value = formData.get(fieldName);

    if (value === null || value.trim() === "") {
        return null;
    }

    return Number(value);
}


function displayAssessment(assessment, result) {
    result.replaceChildren();

    const heading = document.createElement("h3");
    heading.textContent = "Assessment results";
    result.appendChild(heading);

    const medicine = document.createElement("p");
    medicine.textContent = `Medicine: ${assessment.medicine}`;
    result.appendChild(medicine);

    const count = document.createElement("p");
    count.textContent = `Alerts returned: ${assessment.alert_count}`;
    result.appendChild(count);

    if (assessment.alerts.length === 0) {
        const message = document.createElement("p");
        message.textContent =
            "No alerts were generated by the current draft rules. " +
            "This does not mean the medicine is safe.";
        result.appendChild(message);
    } else {
        const list = document.createElement("ul");

        assessment.alerts.forEach((alert) => {
            const item = document.createElement("li");
            item.textContent =
                `${alert.code} (${alert.severity}): ${alert.message}`;
            list.appendChild(item);
        });

        result.appendChild(list);
    }

    const warning = document.createElement("p");
    warning.textContent = assessment.educational_warning;
    result.appendChild(warning);
}
